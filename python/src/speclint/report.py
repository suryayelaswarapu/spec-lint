"""Render lint results as text, JSON, SARIF 2.1.0 or a Markdown migration report."""

from __future__ import annotations

import json
from typing import Any

from speclint import __version__
from speclint.fix import AppliedFix
from speclint.lint import RULES, Finding, summarize

REPO_URL = "https://github.com/suryayelaswarapu/spec-lint"
_SARIF_LEVEL = {"error": "error", "warning": "warning", "info": "note"}


def render_text(findings: list[Finding], filename: str) -> str:
    lines = []
    for f in findings:
        loc = f"{filename}:{f.line}" if f.line else filename
        lines.append(f"{loc}  {f.severity.value:<7}  {f.rule:<26}  {f.message}")
    counts = summarize(findings)
    total = sum(counts.values())
    if total:
        lines.append("")
        lines.append(
            f"{total} problem{'s' if total != 1 else ''} "
            f"({counts['error']} errors, {counts['warning']} warnings, {counts['info']} info)"
        )
    else:
        lines.append(f"{filename}: no problems found")
    return "\n".join(lines) + "\n"


def render_json(findings: list[Finding], filename: str) -> str:
    payload = {
        "tool": "speclint",
        "version": __version__,
        "file": filename,
        "summary": summarize(findings),
        "findings": [f.to_dict() for f in findings],
    }
    return json.dumps(payload, indent=2) + "\n"


def render_sarif(findings: list[Finding], filename: str) -> str:
    """SARIF 2.1.0, accepted by GitHub code scanning (``github/codeql-action/upload-sarif``)."""
    used = sorted({f.rule for f in findings})
    rule_index = {rule_id: i for i, rule_id in enumerate(used)}
    rules = [
        {
            "id": rule_id,
            "shortDescription": {"text": RULES[rule_id].description},
            "helpUri": f"{REPO_URL}/blob/main/docs/rules.md#{rule_id}",
            "defaultConfiguration": {"level": _SARIF_LEVEL[RULES[rule_id].severity.value]},
        }
        for rule_id in used
    ]
    results: list[dict[str, Any]] = []
    for f in findings:
        location: dict[str, Any] = {"artifactLocation": {"uri": filename}}
        if f.line:
            location["region"] = {"startLine": f.line}
        results.append(
            {
                "ruleId": f.rule,
                "ruleIndex": rule_index[f.rule],
                "level": _SARIF_LEVEL[f.severity.value],
                "message": {"text": f.message},
                "locations": [
                    {
                        "physicalLocation": location,
                        "logicalLocations": [{"fullyQualifiedName": f.pointer or "/"}],
                    }
                ],
            }
        )
    sarif = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "speclint",
                        "version": __version__,
                        "informationUri": REPO_URL,
                        "rules": rules,
                    }
                },
                "results": results,
            }
        ],
    }
    return json.dumps(sarif, indent=2) + "\n"


def _md(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_markdown(
    *,
    source: str,
    source_kind: str,
    output: str,
    warnings: list[str],
    fixes: list[AppliedFix],
    findings: list[Finding],
) -> str:
    counts = summarize(findings)
    out = [
        "# spec-lint migration report",
        "",
        f"| Source | Detected format | Output |\n|---|---|---|\n"
        f"| `{source}` | {source_kind} | `{output}` (OpenAPI 3.1) |",
        "",
        "## Summary",
        "",
        f"- Conversion notes: **{len(warnings)}**",
        f"- Auto-fixes applied: **{len(fixes)}**",
        f"- Remaining findings: **{counts['error']}** errors, **{counts['warning']}** warnings, "
        f"**{counts['info']}** info",
        "",
        "## Conversion notes",
        "",
    ]
    out += [f"- {_md(w)}" for w in warnings] or ["_None._"]
    out += ["", "## Auto-fixes applied", ""]
    if fixes:
        out += ["| Rule | Change |", "|---|---|"]
        out += [f"| `{f.rule}` | {_md(f.message)} |" for f in fixes]
    else:
        out.append("_None._")
    out += ["", "## Remaining findings", ""]
    if findings:
        out += ["| Severity | Rule | Line | Message |", "|---|---|---|---|"]
        out += [
            f"| {f.severity.value} | `{f.rule}` | {f.line or ''} | {_md(f.message)} |"
            for f in findings
        ]
    else:
        out.append("_No findings: the contract meets the standard._ ✅")
    out += ["", f"<sub>Generated by spec-lint {__version__}</sub>", ""]
    return "\n".join(out)
